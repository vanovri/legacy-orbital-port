C     SYNTHETIC LEGACY-STYLE RK4 REFERENCE, NOT HISTORICAL SOURCE.
C     FIXED FORM/COMMON/GOTO CORE WITH MODERN IEEE INPUT CHECKS.
      PROGRAM ORBIT66
      USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      CHARACTER*512 LINE
      INTEGER IOS
      LOGICAL INTOKEN
      COMMON /PARAM/ GM, DT, NSTEPS
      COMMON /STATE/ X, Y, VX, VY
      GM = 3.986004418D14
      DT = 1.0D0
      NSTEPS = 10000
      X = 6.778137D6
      Y = 0.0D0
      VX = 0.0D0
      VY = 7.6686D3
C     OPTIONAL ONE-LINE INPUT: STEPS DT GM X Y VX VY.
      READ(*,'(A)',IOSTAT=IOS) LINE
      IF (IOS .GT. 0) STOP 2
      IF (IOS .LT. 0) GOTO 40
      IF (IOS .EQ. 0 .AND. LEN_TRIM(LINE) .GT. 0) THEN
         NTOK = 0
         INTOKEN = .FALSE.
         DO I = 1, LEN_TRIM(LINE)
            IF (LINE(I:I) .EQ. ' ' .OR.
     +          LINE(I:I) .EQ. CHAR(9)) THEN
               INTOKEN = .FALSE.
            ELSE
               IF (INDEX('0123456789+-.EDed',LINE(I:I))
     +             .EQ. 0) STOP 2
               IF (.NOT. INTOKEN) NTOK = NTOK + 1
               INTOKEN = .TRUE.
            ENDIF
         ENDDO
         IF (NTOK .NE. 7) STOP 2
         READ(LINE,*,IOSTAT=IOS) NSTEPS, DT, GM, X, Y, VX, VY
         IF (IOS .NE. 0) STOP 2
      ENDIF
C     THE INPUT CONTRACT ALLOWS ONLY ONE NONEMPTY RECORD.
   30 READ(*,'(A)',IOSTAT=IOS) LINE
      IF (IOS .GT. 0) STOP 2
      IF (IOS .EQ. 0) THEN
         IF (LEN_TRIM(LINE) .GT. 0) STOP 2
         GOTO 30
      ENDIF
   40 IF (.NOT. IEEE_IS_FINITE(GM)) STOP 2
      IF (.NOT. IEEE_IS_FINITE(DT)) STOP 2
      IF (.NOT. IEEE_IS_FINITE(X)) STOP 2
      IF (.NOT. IEEE_IS_FINITE(Y)) STOP 2
      IF (.NOT. IEEE_IS_FINITE(VX)) STOP 2
      IF (.NOT. IEEE_IS_FINITE(VY)) STOP 2
      IF (GM .LT. 0D0 .OR. GM .GT. 1D20) STOP 2
      IF (DT .LE. 0D0 .OR. DT .GT. 60D0) STOP 2
      IF (NSTEPS .LT. 0 .OR. NSTEPS .GT. 1000000) STOP 2
      IF (X*X + Y*Y .LE. 0D0) STOP 2
      I = 0
   10 IF (I .GE. NSTEPS) GOTO 20
      CALL RK4STP
      I = I + 1
      GOTO 10
   20 IF (.NOT. IEEE_IS_FINITE(X)) STOP 3
      IF (.NOT. IEEE_IS_FINITE(Y)) STOP 3
      IF (.NOT. IEEE_IS_FINITE(VX)) STOP 3
      IF (.NOT. IEEE_IS_FINITE(VY)) STOP 3
      WRITE(*,100) X, Y, VX, VY
  100 FORMAT(4(ES25.17E3, 1X))
      END

      SUBROUTINE ACCEL(PX, PY, AX, AY)
      USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /PARAM/ GM, DT, NSTEPS
      R2 = PX*PX + PY*PY
      IF (.NOT. IEEE_IS_FINITE(R2)) STOP 3
      IF (R2 .LE. 0D0) STOP 3
      R3 = R2 * DSQRT(R2)
      IF (.NOT. IEEE_IS_FINITE(R3)) STOP 3
      IF (R3 .LE. 0D0) STOP 3
      AX = -GM * PX / R3
      AY = -GM * PY / R3
      RETURN
      END

      SUBROUTINE RK4STP
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
C     I-N ARE IMPLICIT INTEGER. K STAGES MUST BE DOUBLE PRECISION.
      DOUBLE PRECISION K1X, K1Y, K1VX, K1VY
      DOUBLE PRECISION K2X, K2Y, K2VX, K2VY
      DOUBLE PRECISION K3X, K3Y, K3VX, K3VY
      DOUBLE PRECISION K4X, K4Y, K4VX, K4VY
      COMMON /PARAM/ GM, DT, NSTEPS
      COMMON /STATE/ X, Y, VX, VY
      CALL ACCEL(X, Y, AX1, AY1)
      K1X = VX
      K1Y = VY
      K1VX = AX1
      K1VY = AY1
      CALL ACCEL(X+0.5D0*DT*K1X, Y+0.5D0*DT*K1Y, AX2, AY2)
      K2X = VX + 0.5D0*DT*K1VX
      K2Y = VY + 0.5D0*DT*K1VY
      K2VX = AX2
      K2VY = AY2
      CALL ACCEL(X+0.5D0*DT*K2X, Y+0.5D0*DT*K2Y, AX3, AY3)
      K3X = VX + 0.5D0*DT*K2VX
      K3Y = VY + 0.5D0*DT*K2VY
      K3VX = AX3
      K3VY = AY3
      CALL ACCEL(X+DT*K3X, Y+DT*K3Y, AX4, AY4)
      K4X = VX + DT*K3VX
      K4Y = VY + DT*K3VY
      K4VX = AX4
      K4VY = AY4
      X  = X  + (DT/6D0)*(K1X  + 2D0*K2X  + 2D0*K3X  + K4X)
      Y  = Y  + (DT/6D0)*(K1Y  + 2D0*K2Y  + 2D0*K3Y  + K4Y)
      VX = VX + (DT/6D0)*(K1VX + 2D0*K2VX + 2D0*K3VX + K4VX)
      VY = VY + (DT/6D0)*(K1VY + 2D0*K2VY + 2D0*K3VY + K4VY)
      RETURN
      END
